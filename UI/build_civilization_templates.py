"""Embed editable skin SVGs so runtime palette creation also works in exported PCKs."""
from pathlib import Path
import json
root = Path(__file__).resolve().parent
names = [f'{family}_{state}' for family in ('standard', 'primary') for state in ('normal', 'hover', 'selected', 'hover_pressed', 'disabled')]
buttons = {name: (root / 'Skins' / f'{name}.svg').read_text() for name in names}
window = (root / 'Skins/window.svg').read_text()
(root / 'CivilizationTemplates.gd').write_text('# Generated by UI/build_civilization_templates.py; edit UI/Skins/*.svg instead.\nextends RefCounted\n\nconst BUTTONS = ' + json.dumps(buttons, ensure_ascii=False, indent=2) + '\n\nconst WINDOW = ' + json.dumps(window, ensure_ascii=False) + '\n')
